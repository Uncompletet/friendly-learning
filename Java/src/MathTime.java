public class MathTime {
    public static void main(String[] args) {

        //System.out.println(Math.PI);
        //System.out.println(Math.E);

        double result;

        result = Math.pow(2, 5); // 2 to the power of 5
        result = Math.abs(-5); // Absolute number. (Try to think of it as: How many steps to 0
        result = Math.sqrt(9); // What is the square of 9
        result = Math.round(3.14); // Round 3.14
        result = Math.ceil(3.14); // Round 3.14 up
        result = Math.floor(3.99); // Round 3.99 down
        result = Math.max(10, 20); // What is the max value from the given numbers
        result = Math.min(10, 20); // What is the min value from the given numbers

        System.out.println(result);
    }
}
